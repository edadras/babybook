<?php

namespace App\Services\StoryStudio\Support;

use App\Services\StoryStudio\Exceptions\MediaProcessingException;
use Illuminate\Support\Facades\Log;
use Symfony\Component\Process\Process;

/**
 * Thin wrapper around the ffmpeg / ffprobe binaries.
 */
class Ffmpeg
{
    /**
     * @param  list<string>  $arguments  arguments after the binary
     */
    public function run(array $arguments, ?int $timeout = null): string
    {
        $process = new Process(
            [config('story-studio.ffmpeg.ffmpeg', 'ffmpeg'), '-hide_banner', '-loglevel', 'error', '-y', ...$arguments],
            null,
            null,
            null,
            $timeout ?? (int) config('story-studio.ffmpeg.timeout', 1800),
        );
        $process->run();

        if (! $process->isSuccessful()) {
            $error = trim($process->getErrorOutput()) ?: trim($process->getOutput());
            Log::channel(config('story-studio.log_channel'))->error('story-studio.ffmpeg_failed', [
                'arguments' => array_slice($arguments, 0, 40),
                'error' => mb_substr($error, -2000),
            ]);

            throw new MediaProcessingException('FFmpeg: '.mb_substr($error, -600));
        }

        return $process->getOutput();
    }

    /**
     * Media duration in milliseconds.
     */
    public function durationMs(string $path): int
    {
        $process = new Process([
            config('story-studio.ffmpeg.ffprobe', 'ffprobe'), '-v', 'error',
            '-show_entries', 'format=duration', '-of', 'default=noprint_wrappers=1:nokey=1', $path,
        ], null, null, null, 60);
        $process->run();

        if (! $process->isSuccessful()) {
            throw new MediaProcessingException('ffprobe: '.trim($process->getErrorOutput()));
        }

        return (int) round(((float) trim($process->getOutput())) * 1000);
    }

    /**
     * Escape a path for use inside a filtergraph option (e.g. subtitles=...).
     */
    public static function filterPath(string $path): string
    {
        // Paths are generated by the studio (uuid based), so only ':' and '\\' need escaping.
        return str_replace(['\\', ':'], ['/', '\\:'], $path);
    }

    public static function seconds(int $milliseconds): string
    {
        return number_format($milliseconds / 1000, 3, '.', '');
    }
}
